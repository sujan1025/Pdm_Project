"""
Database Models

This file defines the database tables used by the Flask application.
It stores user accounts and prediction history records.
"""

from datetime import datetime, timezone

import bcrypt
from flask_login import UserMixin
from flask_sqlalchemy import SQLAlchemy


# Create the SQLAlchemy database object
db = SQLAlchemy()


class User(UserMixin, db.Model):
    """
    This model stores user login details and user roles.
    """

    # Unique user ID
    id = db.Column(db.Integer, primary_key=True)

    # Username used for login
    username = db.Column(db.String(80), unique=True, nullable=False, index=True)

    # Hashed password stored securely
    password_hash = db.Column(db.String(255), nullable=False)

    # User role, for example admin or engineer
    role = db.Column(db.String(20), nullable=False, default="engineer")

    # Connect each user to their prediction history records
    predictions = db.relationship(
        "PredictionHistory",
        backref="user",
        lazy=True,
        cascade="all, delete-orphan",
    )

    def set_password(self, password):
        """
        Hash the plain password before storing it.
        """
        password_bytes = password.encode("utf-8")
        hashed_password = bcrypt.hashpw(password_bytes, bcrypt.gensalt())
        self.password_hash = hashed_password.decode("utf-8")

    def check_password(self, password):
        """
        Check whether the entered password matches the stored password hash.
        """
        password_bytes = password.encode("utf-8")
        hashed_bytes = self.password_hash.encode("utf-8")
        return bcrypt.checkpw(password_bytes, hashed_bytes)


class PredictionHistory(db.Model):
    """
    This model stores prediction records made by users.
    """

    # Unique prediction record ID
    id = db.Column(db.Integer, primary_key=True)

    # ID of the user who made the prediction
    user_id = db.Column(db.Integer, db.ForeignKey("user.id"), nullable=False)

    # Input values submitted through the prediction form
    machine_type = db.Column(db.String(1), nullable=False)
    air_temperature = db.Column(db.Float, nullable=False)
    process_temperature = db.Column(db.Float, nullable=False)
    rotational_speed = db.Column(db.Float, nullable=False)
    torque = db.Column(db.Float, nullable=False)
    tool_wear = db.Column(db.Float, nullable=False)

    # Prediction output generated by the machine learning model
    prediction = db.Column(db.Integer, nullable=False)
    failure_probability = db.Column(db.Float, nullable=False)
    status = db.Column(db.String(120), nullable=False)
    recommendation = db.Column(db.String(255), nullable=False)

    # Date and time when the prediction was created
    created_at = db.Column(
        db.DateTime,
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )